<h3>Welcome to Tanoko!</h3>
<p>
  Tanoko is a dictionary and spaced repetition flashcard system for English speakers learning
  Mandarin and/or Japanese. It's faster than typical online dictionaries because the full dictionary
  data files are downloaded and cached locally on your device, and queries happen against these
  local files instead of running on a server. This also means you can do your SRS reviews while
  offline if you've installed Tanoko as a PWA. Tanoko is <a href="https://github.com/invpt/tanoko"
    >open source</a
  >.
</p>
